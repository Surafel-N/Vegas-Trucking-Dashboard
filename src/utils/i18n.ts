for (const [key, val] of Object.entries(CATEGORY_TRANSLATIONS)) {
  NORMALIZED_CATEGORY_MAP.set(normalizeCategoryKey(key), val);
}

// Traduction dynamique ultra-robuste des catégories selon la langue
