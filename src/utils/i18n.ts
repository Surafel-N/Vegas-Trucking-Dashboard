// Traduction dynamique d'un commentaire / texte quelconque selon la langue
export function translateComment(text: string | null | undefined, lang: Language): string {
  if (!text) return "";
  if (lang === 'FR') return text;

  let translated = String(text);
  for (const [regex, replacement] of PHRASE_TRANSLATIONS) {
    translated = translated.replace(regex, replacement);
  }
  return translated;
}

export function translateStatus(status: string, lang: Language): string {
  if (lang === 'FR' || !status) return status;
  const s = status.toLowerCase();
  if (s === 'paid' || s === 'solde' || s === 'soldé' || s === 'payee' || s === 'payée') return 'Paid in full';
  if (s === 'partial' || s === 'partiel' || s === 'partielle') return 'Partial';
  if (s === 'pending' || s === 'en attente') return 'Pending';
  if (s === 'overdue' || s === 'en retard') return 'Overdue';
  if (s === 'active' || s === 'actif') return 'Active';
  if (s === 'inactive' || s === 'inactif') return 'Inactive';
  return status;
}

export function translatePaymentMethod(method: string, lang: Language): string {
  if (lang === 'FR' || !method) return method;
  const m = method.toLowerCase();
  if (m.includes('virement')) return 'Bank Wire';
  if (m.includes('chèque') || m.includes('cheque')) return 'Check';
  if (m.includes('espèce') || m.includes('espece') || m.includes('cash')) return 'Cash';
  if (m.includes('wave') || m.includes('mobile')) return 'Mobile Money / Wave';
  return method;
}
